// Writes src/sim/zones/oganiru-roots.js: the slim tree's roots as they are drawn (5 November 2026, the owner's brief
// "feet on the ground": down Oganiru City's middle strips the slim trees, the habitation's, stand on buttress roots
// spread 1.6 m round their trunks at their usual size, and people stood in them; the trunk alone, 30 cm round, was solid).
//
// From the habitation's copy of the owner's model (the file the page draws, as it is): every face of it low enough to be
// a root (some of it within 60 cm of its foot at its usual size) and reaching out beyond where it is solid (oganiru.js:
// within 0.045 of its unit of its trunk's middle, where its buttresses stand half a metre and more), in the model's own
// frame about the middle of its foot, its own units, as whole numbers of hundred-thousandths. The game stands people on
// the highest of them over a point, at the size and turn each tree is drawn (oganiru.js `slimRootTop`).
//
//   node tools/city/slim-roots.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { parseGLB } from '../../src/client/glb.js';
import { HABITATION_MODELS } from '../../src/sim/zones/habitation-scene.js';

const LOW = 0.04, OUT = 0.04;
const info = HABITATION_MODELS.slimtree;
const buf = readFileSync(new URL('../../../site/habitation/slimtree.full.glb', import.meta.url));
const { json, accessor } = parseGLB(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const prim = json.meshes[0].primitives[0];
const pos = accessor(prim.attributes.POSITION).array, index = accessor(prim.indices).array;
const tris = [];
let reach = 0;
for (let t = 0; t < index.length; t += 3) {
  const p = [0, 1, 2].map((j) => { const k = index[t + j]; return [pos[k * 3] - info.base[0], pos[k * 3 + 1] - info.base[1], pos[k * 3 + 2] - info.base[2]]; });
  if (Math.min(...p.map((q) => q[1])) > LOW || Math.max(...p.map((q) => Math.hypot(q[0], q[2]))) < OUT) continue;
  reach = Math.max(reach, ...p.map((q) => Math.hypot(q[0], q[2])));
  tris.push(...p.flat().map((v) => Math.round(v * 1e5)));
}
writeFileSync(new URL('../../src/sim/zones/oganiru-roots.js', import.meta.url),
  '// Generated by tools/city/slim-roots.mjs from the habitation\'s copy of the owner\'s slim tree. Do not edit by hand.\n' +
  '// Its roots as they are drawn: the faces of it low enough to be a root and reaching out beyond its solid trunk, in its\n' +
  '// own frame about the middle of its foot, its own units (x, y up, z), as whole numbers of hundred-thousandths, nine to\n' +
  '// a face; and how far out from its foot they reach.\n' +
  `export const SLIM_ROOTS = Object.freeze({ reach: ${reach.toFixed(4)}, tris: Object.freeze(${JSON.stringify(tris)}) });\n`);
console.log(`written: src/sim/zones/oganiru-roots.js, ${tris.length / 9} faces reaching ${reach.toFixed(3)} of its unit`);
