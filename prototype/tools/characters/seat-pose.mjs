// Writes src/client/seat-pose.js: one moment of the supplied woman's own "sit" animation (sit.001 at 1.0 s),
// as a rotation for each bone. Both supplied figures share the same skeleton names, so this one sitting pose
// seats either of them in a vehicle. Only rotations are taken: each figure keeps its own bone lengths.
// Nothing is written to either GLB.
//
//   node tools/characters/seat-pose.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { parseGLB } from '../../src/client/glb.js';

const AT = 1.0;
const file = readFileSync(new URL('../../assets/characters/figures/animated/woman.glb', import.meta.url));
const parsed = parseGLB(file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength));
const sit = parsed.animations.find((a) => a.name === 'sit.001');
if (!sit) throw new Error('the woman file has no sit.001');
const pose = {};
for (const t of sit.tracks) {
  if (t.path !== 'rotation') continue;
  let k = 0;
  for (let i = 0; i < t.times.length; i += 1) if (Math.abs(t.times[i] - AT) < Math.abs(t.times[k] - AT)) k = i;
  pose[t.node] = Array.from(t.values.slice(k * 4, k * 4 + 4), (v) => +v.toFixed(5));
}
writeFileSync(new URL('../../src/client/seat-pose.js', import.meta.url),
  `// Generated by tools/characters/seat-pose.mjs from the supplied woman's sit.001 at ${AT} s. Do not edit by hand.\nexport const SEAT_POSE = ${JSON.stringify(pose)};\n`);
console.log(`seat pose: ${Object.keys(pose).length} bones`);
