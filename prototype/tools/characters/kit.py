"""Writes the character kit the game loads: one manifest and one packed binary, as a JavaScript module.

Every part is skinned to the one skeleton of the base character. Vertices are
packed small: positions and texture coordinates in 16 bits, normals, bone
indices, weights, colour slot and shade in 8.
"""
import base64, json
import numpy as np

POS_RANGE = 1.25          # metres either side of the origin; height runs from -0.25 to 2.25
POS_LIFT = 1.0
UV_SCALE = 2048.0
SHADE_ONE = 200.0         # a shade byte of 200 leaves the colour as it is

# colour slots: what paints a vertex
SLOTS = {'skin': 0, 'hair': 1, 'lips': 2, 'eyewhite': 3, 'dark': 4, 'nail': 5, 'brow': 6, 'iris': 7, 'a': 8, 'b': 9, 'c': 10, 'd': 11}


class Kit:
    def __init__(self, bones):
        self.bones = bones
        self.parts = {}
        self.blob = bytearray()
        self.extra = {}
        self._seen = {}

    def _put(self, array):
        while len(self.blob) % 4: self.blob.append(0)
        off = len(self.blob)
        self.blob += array.tobytes()
        return off

    def add(self, part_id, mesh, lod=0, **meta):
        # the same mesh given for two levels is stored once
        key = (part_id, id(mesh))
        if key in self._seen:
            part = self.parts[part_id]
            while len(part['lods']) <= lod: part['lods'].append(None)
            part['lods'][lod] = self._seen[key]
            return
        n = len(mesh['pos'])
        assert n < 65536, f'{part_id}: {n} vertices is too many for 16-bit indices'
        p = mesh['pos'].copy(); p[:, 1] -= POS_LIFT
        assert np.abs(p).max() < POS_RANGE, f'{part_id}: reaches outside the packing box'
        pos = np.round(p / POS_RANGE * 32767).astype('<i2')
        nrm = np.round(np.clip(mesh['nrm'], -1, 1) * 127).astype(np.int8)
        uv = np.round(np.clip(mesh['uv'] * UV_SCALE, -32767, 32767)).astype('<i2')
        W = np.round(mesh['W'] * 255).astype(np.int64)
        W[:, 0] += 255 - W.sum(1)           # weights must add to exactly one
        assert W.min() >= 0
        rec = {'v': n, 't': len(mesh['idx']),
               'pos': self._put(pos), 'nrm': self._put(nrm), 'uv': self._put(uv),
               'joints': self._put(mesh['J'].astype(np.uint8)), 'weights': self._put(W.astype(np.uint8)),
               'slot': self._put(mesh['slot'].astype(np.uint8)),
               'shade': self._put(np.round(np.clip(mesh['shade'] * SHADE_ONE, 0, 255)).astype(np.uint8)),
               'idx': self._put(mesh['idx'].astype('<u2'))}
        self._seen[key] = rec
        part = self.parts.setdefault(part_id, {'lods': [], **meta})
        part.update(meta)
        while len(part['lods']) <= lod: part['lods'].append(None)
        part['lods'][lod] = rec
        slots = sorted(set(int(s) for s in np.unique(mesh['slot'])))
        part['slots'] = sorted(set(part.get('slots', [])) | set(slots))
        lo = mesh['pos'].min(0); hi = mesh['pos'].max(0)
        part['box'] = [round(float(x), 3) for x in np.r_[lo, hi]]

    def manifest(self):
        bones = []
        for b in self.bones:
            bones.append({'name': b['name'], 'parent': b['parent'], 't': [round(float(x), 6) for x in b['t']], 'r': [round(float(x), 6) for x in b['r']],
                          'head': [round(float(x), 5) for x in b['world'][:3, 3]],
                          'ibm': [round(float(x), 6) for x in b['ibm'].T.ravel()]})          # column-major, as three.js keeps it
        return {'version': 1, 'posRange': POS_RANGE, 'posLift': POS_LIFT, 'uvScale': UV_SCALE, 'shadeOne': SHADE_ONE, 'slots': SLOTS, 'bones': bones, **self.extra, 'parts': self.parts, 'bytes': len(self.blob)}

    def write(self, path):
        meta = self.manifest()
        text = '// Generated by tools/characters/bake.py from assets/characters. Do not edit by hand.\n'
        text += 'export const KIT_META = ' + json.dumps(meta, separators=(',', ':')) + ';\n'
        text += "export const KIT_B64 = '" + base64.b64encode(bytes(self.blob)).decode('ascii') + "';\n"
        open(path, 'w').write(text)
        return meta
