// Writes src/sim/zones/habitation-wood.js: the habitation's trees' wood lower than a walker's height, as it is drawn
// (5 November 2026, the owner's brief "feet on the ground": the big trees' buttresses and roots are solid from 0.9 to
// 1.8 m up, habitation-roots.js; lower than that, up to 80 cm high, people stood in them).
//
// From the habitation's copies of the owner's models (the files the page draws, as they are): of each tree, palm and
// banana, every face of its wood (its first part: trunk, buttresses, roots, branches; not its leaves or the shade inside
// its crown) some of which is within a walker's height of its foot at the largest it stands anywhere, in the model's own
// frame about the middle of its foot, its own units, as whole numbers of hundred-thousandths, nine to a face; and how far
// out from its foot they reach. The game stands people on the highest of them over a point, at the size and turn each
// copy is drawn (habitation.js `habitationWoodY`).
//
//   node tools/habitation/low-wood.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { parseGLB } from '../../src/client/glb.js';
import { HABITATION_MODELS, HABITATION_STANDING } from '../../src/sim/zones/habitation-scene.js';

const WALKER = 1.0;       // metres: wood lower than this over the foot is stood on (above 0.9 it is solid as well)
const out = {}, report = [];
for (const [m, info] of Object.entries(HABITATION_MODELS)) {
  if (!['tree', 'palm', 'banana'].includes(info.kind)) continue;
  const copies = HABITATION_STANDING.filter((p) => p.m === m && p.y === null);
  if (!copies.length) continue;
  const most = Math.max(...copies.map((p) => p.s / info.unit));
  const buf = readFileSync(new URL(`../../../site/habitation/${m}.full.glb`, import.meta.url));
  const { json, accessor } = parseGLB(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  // (its wood: the part named so, else its first)
  const prims = json.meshes.flatMap((mesh) => mesh.primitives);
  const named = (p) => (json.materials && json.materials[p.material] ? json.materials[p.material].name : '');
  const wood = prims.find((p) => named(p) === 'surface') || prims[0];
  const pos = accessor(wood.attributes.POSITION).array;
  const index = wood.indices !== undefined ? accessor(wood.indices).array : Uint32Array.from({ length: pos.length / 3 }, (_, i) => i);
  const tris = [];
  let reach = 0;
  for (let t = 0; t < index.length; t += 3) {
    const p = [0, 1, 2].map((j) => { const k = index[t + j]; return [pos[k * 3] - info.base[0], pos[k * 3 + 1] - info.base[1], pos[k * 3 + 2] - info.base[2]]; });
    if (Math.min(...p.map((q) => q[1])) * most > WALKER) continue;
    reach = Math.max(reach, ...p.map((q) => Math.hypot(q[0], q[2])));
    tris.push(...p.flat().map((v) => Math.round(v * 1e5)));
  }
  if (!tris.length) continue;
  out[m] = { reach: +reach.toFixed(4), tris };
  report.push(`${m.padEnd(24)} ${String(tris.length / 9).padStart(6)} faces, out to ${(reach * most).toFixed(1)} m at its largest (${copies.length} standing)`);
}
writeFileSync(new URL('../../src/sim/zones/habitation-wood.js', import.meta.url),
  '// Generated by tools/habitation/low-wood.mjs from the habitation\'s copies of the owner\'s models. Do not edit by hand.\n' +
  '// Each tree\'s, palm\'s and banana\'s wood lower than a walker\'s height, as drawn: faces in its own frame about the middle\n' +
  '// of its foot, its own units (x, y up, z), as whole numbers of hundred-thousandths, nine to a face; and how far out\n' +
  '// from its foot they reach.\n' +
  `export const HABITATION_WOOD = Object.freeze(${JSON.stringify(out)});\n`);
console.log(report.join('\n'));
console.log(`written: src/sim/zones/habitation-wood.js, ${Object.keys(out).length} models`);
