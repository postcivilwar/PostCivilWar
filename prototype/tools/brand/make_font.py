PIXEL = 125          # font units to a pixel: eight pixels to the em
NAMES = {'.': 'period', ',': 'comma', ':': 'colon', '!': 'exclam', '?': 'question', '-': 'hyphen', "'": 'quotesingle', '/': 'slash', '+': 'plus', '%': 'percent', '=': 'equal', '£': 'sterling', ' ': 'space',
         '0': 'zero', '1': 'one', '2': 'two', '3': 'three', '4': 'four', '5': 'five', '6': 'six', '7': 'seven', '8': 'eight', '9': 'nine'}


def outline(rows):
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        y1 = (7 - r) * PIXEL
        y0 = y1 - PIXEL
        c = 0
        while c < len(row):
            if row[c] != '#':
                c += 1
                continue
            start = c
            while c < len(row) and row[c] == '#':
                c += 1
            x0, x1 = start * PIXEL, c * PIXEL
            pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
    return pen.glyph()


def build(path):
    for ch, rows in GLYPHS.items():
        assert len(rows) == 7 and len({len(r) for r in rows}) == 1, ch
    order = ['.notdef']
    cmap = {}
    glyphs = {'.notdef': outline(["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"])}
    widths = {'.notdef': (6 * PIXEL, 0)}
    for ch, rows in GLYPHS.items():
        name = NAMES.get(ch, ch)
        order.append(name)
        glyphs[name] = outline(rows)
        widths[name] = ((len(rows[0]) + 1) * PIXEL, 0)
        cmap[ord(ch)] = name
        if ch.isalpha():
            cmap[ord(ch.lower())] = name
    cmap[0xA0] = 'space'
    cmap[0x2019] = 'quotesingle'
    cmap[0xB7] = 'period'
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(widths)
    fb.setupHorizontalHeader(ascent=7 * PIXEL, descent=-PIXEL)
    fb.setupNameTable({'familyName': 'PCW Arcade', 'styleName': 'Regular', 'copyright': 'Made for PostCivilWar. Original glyphs.'})
    fb.setupOS2(sTypoAscender=7 * PIXEL, sTypoDescender=-PIXEL, sTypoLineGap=0, usWinAscent=7 * PIXEL, usWinDescent=PIXEL, sCapHeight=7 * PIXEL, sxHeight=7 * PIXEL)
    fb.setupPost()
    fb.save(path)
    return len(order) - 1


