"""Bakes the story slides into the page's data.

The five supplied slides (assets/brand/slides, 1920 by 1080, captions drawn in)
are kept as supplied; two have a retouched copy beside them (retouch.py), which
is the one used. For the page they are scaled to 1280 by 720 and written
into src/client/brand-data.js as data URIs, in the story order the hand-off
note gives. The fourth slide of the story was never delivered and is not
invented here.

    python3 tools/brand/bake.py
"""
import base64
import io
import json
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
SLIDES = [
    ('01_the_war_ended_1080p.jpg', 'The war ended. 15 January 1970. Biafra surrendered. The silence that followed was not peace.'),
    ('02_home_had_changed_1080p.jpg', 'Home had changed. Soldiers returned. But home was no longer the same.'),
    ('03_what_remained_1080p.jpg', 'What remained. Hunger. Poverty. Loss. Silence.'),
    ('05_voices_from_the_ruins_1080p.jpg', 'Voices from the ruins. Loss did not erase their voices.'),
    ('06_learning_to_live_1080p.jpg', 'Learning to live. They rebuilt from the ruins. Peace meant living with what war had taken.'),
]
SIZE = (1280, 720)


def main():
    rows = []
    total = 0
    for name, alt in SLIDES:
        # a slide that has been retouched (tools/brand/retouch.py) is used in place of the supplied one
        folder = os.path.join(ROOT, 'assets', 'brand', 'slides')
        retouched = os.path.join(folder, 'retouched', name)
        image = Image.open(retouched if os.path.exists(retouched) else os.path.join(folder, name)).convert('RGB').resize(SIZE, Image.LANCZOS)
        out = io.BytesIO()
        image.save(out, 'JPEG', quality=78, optimize=True, progressive=True)
        data = out.getvalue()
        total += len(data)
        rows.append({'id': name.split('_1080p')[0], 'alt': alt, 'src': 'data:image/jpeg;base64,' + base64.b64encode(data).decode('ascii')})
    with open(os.path.join(ROOT, 'src', 'client', 'brand-data.js'), 'w') as f:
        f.write('// Generated by tools/brand/bake.py from assets/brand/slides. Do not edit.\n')
        f.write('export const STORY_SLIDES = ' + json.dumps(rows) + ';\n')
    print(f'{len(rows)} slides, {total // 1024} KB of JPEG')


if __name__ == '__main__':
    main()
