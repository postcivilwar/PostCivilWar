"""Bakes the game's cover into the page's data.

The cover is one supplied illustration, taken apart by tools/brand/cover.py into a plate (the picture without
its lettering), the name, the four lines of words and the painted PLAY button. Here those pieces are scaled for
a screen and written into src/client/brand-data.js as data URIs, with where each one sat in the picture, so
that the page can put them back: exactly as supplied on a 16:9 screen, rearranged on a tall one.

    python3 tools/brand/cover.py     (only when the supplied picture changes)
    python3 tools/brand/bake.py
"""
import base64
import io
import json
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
COVER = os.path.join(ROOT, 'assets', 'brand', 'cover')
PLATE_WIDTH = 2000          # the plate as the page carries it; the supplied picture is 2576 wide


def uri(image, kind, **how):
    out = io.BytesIO()
    image.save(out, kind, **how)
    data = out.getvalue()
    return 'data:image/' + kind.lower() + ';base64,' + base64.b64encode(data).decode('ascii'), len(data)


def main():
    with open(os.path.join(COVER, 'cover.json')) as f:
        where = json.load(f)
    W, H = where['size']
    scale = PLATE_WIDTH / W
    total = 0
    plate = Image.open(os.path.join(COVER, 'plate.jpg')).convert('RGB').resize((PLATE_WIDTH, round(H * scale)), Image.LANCZOS)
    # (as WebP since 20 October 2026: 149 KB where the same picture as JPEG was 267 KB, and the cover is what a phone
    # waits for before PLAY)
    src, size = uri(plate, 'WEBP', quality=86, method=6)
    total += size
    cover = {
        'alt': 'Post Civil War. A woman and a man stand on a quay between a yacht and a jet. Find work. Buy a plot. Build the walls. Start again.',
        # every place below is in the plate's own measure: 0..1 of its width and of its height
        'aspect': W / H,
        'sky': '#%02x%02x%02x' % tuple(where['sky']),
        'figures': [where['figures'][0] / W, where['figures'][1] / H, where['figures'][2] / W, where['figures'][3] / H],
        'plate': src,
    }
    for name, box in (('logo', 'logo'), ('words', 'words'), ('play', 'play')):
        piece = Image.open(os.path.join(COVER, name + '.png')).convert('RGBA')
        piece = piece.resize((round(piece.width * scale), round(piece.height * scale)), Image.LANCZOS)
        src, size = uri(piece, 'WEBP', quality=92, method=6)
        total += size
        x, y, w, h = where[box]
        cover[name] = {'src': src, 'x': x / W, 'y': y / H, 'w': w / W, 'h': h / H, 'ratio': w / h}
    with open(os.path.join(ROOT, 'src', 'client', 'brand-data.js'), 'w') as f:
        f.write('// Generated by tools/brand/bake.py from assets/brand/cover. Do not edit.\n')
        f.write('export const COVER = ' + json.dumps(cover) + ';\n')
    print(f'the cover: {total // 1024} KB in four pieces')


if __name__ == '__main__':
    main()
