// The town's voices (28 October 2026): writes src/sim/voice-lines.js from the script (assets/voices/script.csv) and
// the light copies of the recordings (assets/voices/game/, made by tools/voices/game_copies.py, with their lengths in
// assets/voices/game/_lengths.json). A line with no recording is left out, and a conversation is used only whole, so
// the game never waits for a voice that is not there.
//   node tools/voices/data.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { readScript } from './script.mjs';

const root = new URL('../../', import.meta.url);
const lengthsFile = new URL('assets/voices/game/_lengths.json', root);
const lengths = existsSync(lengthsFile) ? JSON.parse(readFileSync(lengthsFile, 'utf8')) : {};
// (`--estimated`: every line at the length the script gives it, as if recorded: only to try the town with them all)
const { cast, talks, reactions, total, recorded, conversations } = readScript({ lengths, estimated: process.argv.includes('--estimated') });
const out = `// The town's voices: generated by tools/voices/data.mjs from assets/voices/script.csv and the recordings' light copies
// (assets/voices/game/). Do not edit by hand. ${recorded} of the script's ${total} lines are recorded; ${talks.length} of its
// ${conversations} conversations are whole.
//
// VOICE_CAST       a voice -> { who: the person in the game ('n:<index>' a townsperson, 'r:<id>' one of the people at
//                  the counters, null a figure not in the game yet), name }
// VOICE_TALKS      the conversations, each { id, when, lines: [[voice, line id, seconds, words, meaning]] }, said in turn
// VOICE_REACTIONS  voice -> what happened -> [[line id, seconds, words, meaning]]
export const VOICE_CAST = Object.freeze(${JSON.stringify(cast)});
export const VOICE_TALKS = Object.freeze(${JSON.stringify(talks)});
export const VOICE_REACTIONS = Object.freeze(${JSON.stringify(reactions)});
`;
writeFileSync(new URL('src/sim/voice-lines.js', root), out);
const missing = Object.entries(cast).filter(([, c]) => !c.who).map(([k]) => k);
console.log(`voices: ${Object.keys(cast).length}; lines recorded ${recorded} of ${total}; conversations whole ${talks.length} of ${conversations}; not in the game yet: ${missing.join(', ') || 'none'}`);
